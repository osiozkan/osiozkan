//! Aegisub'ın kendi kara-templater.lua betiğinin osisub Lua ortamında birebir çalıştığını doğrular.
use osisub_core::ass::Script;
use osisub_lua::{Engine, HeadlessHost};
use std::path::Path;

#[test]
fn kara_templater_generates_fx_lines() {
    let mut e = Engine::new(Box::new(HeadlessHost { quiet: true, ..Default::default() })).unwrap();
    e.set_script(Script::parse(&std::fs::read_to_string("tests/fixtures/templater.ass").unwrap()));
    e.load_script(Path::new("lua/autoload/kara-templater.lua")).unwrap();
    let id = e.macros().iter().position(|m| m.name.contains("template")).expect("templater makrosu");
    e.run_macro(id, &[], 0).unwrap();
    let s = e.script();
    let fx: Vec<_> = s.dialogues().filter(|d| d.effect == "fx").collect();
    // "template syl noblank": 4 hece; "template line": 1 satır
    assert_eq!(fx.len(), 5, "{:#?}\nlog: {}", fx.iter().map(|d| &d.text).collect::<Vec<_>>(), e.take_log());
    let syl0 = fx.iter().find(|d| d.text.contains("\\pos(")).unwrap();
    assert!(syl0.text.contains("\\fad(300,200)"), "{}", syl0.text);
    assert!(syl0.text.contains("\\t(0,500,\\1c&H00FFFF&)"), "{}", syl0.text);
    assert_eq!(syl0.start_time, 10000 - 300, "retime start2syl -300");
    // Orijinal karaoke satırı yorum satırına dönüşmeli
    assert!(s.dialogues().any(|d| d.comment && d.effect == "karaoke"));
}

/// Aegisub'ın kaydettiği dosya: Script Info `;` yorumları + `[Aegisub Project Garbage]`.
/// Eskiden Lua bunları "unknown" satır olarak görüyordu ve karaskel.collect_head ilk yorumda durup
/// "No styles were found" hatası veriyordu (gerçek dosyaların neredeyse hepsi).
#[test]
fn aegisub_kaydi_yorum_ve_garbage_ile_calisir() {
    let src = std::fs::read_to_string("tests/fixtures/templater.ass").unwrap().replace("\r\n", "\n"); // Windows checkout CRLF
    let src = src.replacen("[Script Info]\n", "[Script Info]\n; Script generated by Aegisub 3.2.2\n; http://www.aegisub.org/\n", 1);
    let src = src.replacen("\n[V4+ Styles]", "\n[Aegisub Project Garbage]\nVideo File: x.mkv\nActive Line: 3\n\n[V4+ Styles]", 1);
    assert!(src.contains("Garbage") && src.contains("; Script"));
    let mut e = Engine::new(Box::new(HeadlessHost { quiet: true, ..Default::default() })).unwrap();
    e.set_script(Script::parse(&src));
    e.load_script(Path::new("lua/autoload/kara-templater.lua")).unwrap();
    let id = e.macros().iter().position(|m| m.name.contains("template")).expect("templater makrosu");
    e.run_macro(id, &[], 0).unwrap_or_else(|er| panic!("{}", er.message));
    let s = e.script();
    assert_eq!(s.dialogues().filter(|d| d.effect == "fx").count(), 5, "log: {}", e.take_log());
    let out = s.to_ass_string();
    assert!(out.contains("; Script generated by Aegisub") && out.contains("Video File: x.mkv"), "gizli satırlar korunmalı");
}

/// Seçim ve dönen etkin satır gizli satırlar atlanarak eşlenir (Lua 1 = ilk görünür satır).
#[test]
fn secim_gizli_satirlari_atlar() {
    let src = "[Script Info]\n; yorum\nTitle: t\n\n[Aegisub Project Garbage]\nVideo File: x.mkv\n\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\nDialogue: 0,0:00:00.00,0:00:01.00,Default,,0,0,0,,a\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,b\n";
    let dir = std::env::temp_dir().join(format!("osisub-sel-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let lua = dir.join("s.lua");
    std::fs::write(&lua, r##"
script_name="sel"
aegisub.register_macro("sel", "", function(subs, sel, act)
  assert(#subs == 3, "#subs=" .. #subs)            -- Title + 2 diyalog
  assert(subs[1].class == "info" and subs[1].key == "Title")
  assert(sel[1] == 3 and act == 3, "sel=" .. tostring(sel[1]) .. " act=" .. tostring(act))
  local l = subs[3]; l.text = l.text .. "!"; subs[3] = l
  subs.insert(2, l)                                 -- Title'dan sonra, ilk diyalogtan önce
  subs.delete(4)                                    -- eski "b"
  return {2}, 2
end)
"##).unwrap();
    let mut e = Engine::new(Box::new(HeadlessHost { quiet: true, ..Default::default() })).unwrap();
    let sc = Script::parse(src);
    let raw_b = sc.entries.iter().position(|x| matches!(x, osisub_core::ass::Entry::Dialogue(d) if d.text == "b")).unwrap();
    e.set_script(sc);
    e.load_script(&lua).unwrap();
    let out = e.run_macro(0, &[raw_b + 1], raw_b + 1).unwrap_or_else(|er| panic!("{}", er.message));
    let s = e.script();
    let texts: Vec<_> = s.dialogues().map(|d| d.text.clone()).collect();
    assert_eq!(texts, vec!["b!", "a"]);
    let want = s.entries.iter().position(|x| matches!(x, osisub_core::ass::Entry::Dialogue(d) if d.text == "b!")).unwrap() + 1;
    assert_eq!(out.selection, Some(vec![want]));
    assert_eq!(out.active, Some(want));
    assert!(s.to_ass_string().contains("; yorum"));
}
