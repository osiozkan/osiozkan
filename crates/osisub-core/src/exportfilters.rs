//! Yerleşik dışa aktarım süzgeçleri (Aegisub "Export" penceresindeki yerleşikler + osisub
//! eklemeleri). Belgeye değil, dışa aktarılan kopyaya uygulanır; Lua süzgeçlerinden (ör. karaoke
//! şablonlayıcı) SONRA çalışır — şablon yorumları ancak o zaman silinebilir.
use crate::ass::{Entry, Script, SEC_GARBAGE, SEC_INFO};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Builtins {
    /// Yorum satırlarını ve hiçbir satırın kullanmadığı stilleri sil (Aegisub "Strip comments
    /// and unused styles"; `\r` başvuruları da kullanım sayılır)
    pub strip_comments: bool,
    /// `[Script Info]`'da yalnızca oynatıcının ihtiyaç duyduğu anahtarları bırak, proje çöpünü sil
    /// (Aegisub "Clean Script Info")
    pub clean_info: bool,
    /// Tanımsız stil kullanan satırları `Default`'a çevir (Aegisub "Fix styles")
    pub fix_styles: bool,
    /// Metindeki `{not}` bloklarını sil (osisub)
    pub strip_notes: bool,
    /// Gereksiz etiketleri sil (osisub, core::tagclean)
    pub clean_tags: bool,
}

const KEEP_INFO: &[&str] = &["ScriptType", "PlayResX", "PlayResY", "LayoutResX", "LayoutResY", "WrapStyle", "ScaledBorderAndShadow", "YCbCr Matrix", "Collisions", "PlayDepth", "Kerning", "Title", "Language"];

/// Seçili yerleşik süzgeçleri uygular; değişiklik sayısını döndürür.
pub fn apply(s: &mut Script, b: &Builtins) -> usize {
    let mut n = 0;
    if b.strip_notes || b.clean_tags {
        for e in s.entries.iter_mut() {
            let Entry::Dialogue(d) = e else { continue };
            if d.comment { continue; }
            if b.strip_notes {
                let t = crate::taglint::strip_notes(&d.text);
                if t != d.text { d.text = t; n += 1; }
            }
            if b.clean_tags && !d.effect.eq_ignore_ascii_case("fx") {
                if let Some(t) = crate::tagclean::clean(&d.text) { d.text = t; n += 1; }
            }
        }
    }
    if b.fix_styles {
        let names: Vec<String> = s.styles().map(|st| st.name.clone()).collect();
        let fallback = if names.iter().any(|x| x == "Default") { "Default".to_string() } else { names.first().cloned().unwrap_or_else(|| "Default".into()) };
        for e in s.entries.iter_mut() {
            if let Entry::Dialogue(d) = e {
                if !names.iter().any(|x| x.eq_ignore_ascii_case(&d.style)) {
                    d.style = fallback.clone();
                    n += 1;
                }
            }
        }
    }
    if b.strip_comments {
        let before = s.entries.len();
        s.entries.retain(|e| !matches!(e, Entry::Dialogue(d) if d.comment));
        // kullanılan stiller: satır stilleri + \r başvuruları
        let mut used: std::collections::HashSet<String> = Default::default();
        for d in s.dialogues() {
            used.insert(d.style.to_lowercase());
            for seg in crate::overrides::parse(&d.text) {
                if let crate::overrides::Seg::Block(tags) = seg {
                    for t in tags.iter().filter(|t| t.name == "r" && !t.arg.trim().is_empty()) {
                        used.insert(t.arg.trim().to_lowercase());
                    }
                }
            }
        }
        s.entries.retain(|e| !matches!(e, Entry::Style(st) if !used.contains(&st.name.to_lowercase())));
        n += before - s.entries.len();
    }
    if b.clean_info {
        let before = s.entries.len();
        s.entries.retain(|e| match e {
            Entry::Info { key, .. } => KEEP_INFO.iter().any(|k| k.eq_ignore_ascii_case(key)),
            Entry::Unknown { section, raw } if section == SEC_INFO => !raw.trim_start().starts_with(';'),
            Entry::Unknown { section, .. } => section != SEC_GARBAGE,
            _ => true,
        });
        n += before - s.entries.len();
    }
    n
}

#[cfg(test)]
mod tests {
    use super::*;

    const SRC: &str = "[Script Info]\n; Script generated by Aegisub\nTitle: Bölüm 1\nScriptType: v4.00+\nPlayResX: 1920\nPlayResY: 1080\nOriginal Translation: biri\nYCbCr Matrix: TV.709\n\n[Aegisub Project Garbage]\nVideo File: a.mkv\nActive Line: 3\n\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\nStyle: Default,Arial,48,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1\nStyle: Kullanilmayan,Arial,48,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1\nStyle: Sadece-r,Arial,48,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1\nStyle: Sablon,Arial,48,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,2,2,2,10,10,10,1\n\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\nComment: 0,0:00:00.00,0:00:01.00,Sablon,,0,0,0,template syl,{\\fad(100,100)}\nDialogue: 0,0:00:00.00,0:00:01.00,Default,,0,0,0,,a{\\rSadece-r}b{çevirmen notu}\nDialogue: 0,0:00:01.00,0:00:02.00,Yok,,0,0,0,,{\\fs20\\fs30}c\n";

    #[test]
    fn hepsi() {
        let mut s = Script::parse(SRC);
        let n = apply(&mut s, &Builtins { strip_comments: true, clean_info: true, fix_styles: true, strip_notes: true, clean_tags: true });
        assert!(n > 0);
        let t = s.to_ass_string();
        assert!(!t.contains("Comment:") && !t.contains("Kullanilmayan") && !t.contains("Sablon"), "{t}");
        assert!(t.contains("Style: Sadece-r"), "\\r ile kullanılan stil korunmalı");
        assert!(!t.contains("Project Garbage") && !t.contains("Original Translation") && !t.contains("generated by"), "{t}");
        assert!(t.contains("YCbCr Matrix: TV.709") && t.contains("PlayResX: 1920") && t.contains("Title: Bölüm 1"));
        assert!(t.contains(",Default,,0,0,0,,{\\fs30}c"), "{t}");
        assert!(t.contains("a{\\rSadece-r}b\n") || t.contains("a{\\rSadece-r}b\r\n"), "{t}");
    }

    #[test]
    fn hicbiri_secili_degilse_degismez() {
        let mut s = Script::parse(SRC);
        let before = s.to_ass_string();
        assert_eq!(apply(&mut s, &Builtins::default()), 0);
        assert_eq!(s.to_ass_string(), before);
    }
}
