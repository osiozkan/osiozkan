"""Automation 4 çalışma zamanı testleri (arayüzsüz)."""

import glob
import os
import unittest

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from osisub import config  # noqa: E402
from osisub.automation.host import HeadlessHost  # noqa: E402
from osisub.automation.runtime import LUA_FLAVOR, LuaScript, ScriptManager  # noqa: E402
from osisub.core.assfile import AssDocument, Event  # noqa: E402
from osisub.core.framemap import FrameMap  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SAMPLE = os.path.join(HERE, "fixtures", "sample.ass")
INC = [config.builtin_include_dir()]


def load(path, host=None):
    sc = LuaScript(path, INC, host or HeadlessHost())
    assert sc.load(), sc.error
    return sc


def macro(sc, name):
    return next(m for m in sc.macros if m.name == name)


class TestApi(unittest.TestCase):
    def test_api_checks(self):
        host = HeadlessHost()
        sc = load(os.path.join(HERE, "lua", "test_api.lua"), host)
        doc = AssDocument.load(SAMPLE)
        r = sc.run_macro(macro(sc, "API"), doc, [0], 0)
        self.assertEqual(r.status, "ok", r.error)
        log = "".join(m for _, m in host.log_lines)
        fails = [ln for ln in log.splitlines() if ln.startswith("FAIL")]
        self.assertIn("DONE", log)
        self.assertEqual(fails, [], "\n".join(fails))
        self.assertEqual(log.count("OK "), len([ln for ln in log.splitlines() if ln.startswith("OK")]))

    def test_luajit(self):
        self.assertIn("LuaJIT", LUA_FLAVOR)


class TestMacros(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.host = HeadlessHost()
        cls.sc = load(os.path.join(HERE, "lua", "test_macros.lua"), cls.host)

    def run_m(self, name, sel, active=None, doc=None):
        doc = doc or AssDocument.load(SAMPLE)
        r = self.sc.run_macro(macro(self.sc, name), doc, sel, sel[0] if active is None else active)
        return doc, r

    def test_upper_and_undo_point(self):
        doc, r = self.run_m("Test/Büyük harf", [0, 4])
        self.assertEqual(r.status, "ok")
        self.assertEqual(doc.events[0].text, "{\\AN8}MERHABA DÜNYA, NASILSIN?")
        self.assertEqual(r.selection, [0, 4])
        self.assertIn("Büyük harf", r.undo_points)

    def test_split_inserts(self):
        doc, r = self.run_m("Test/Böl", [4])
        self.assertEqual(len(doc.events), 7)
        self.assertEqual((doc.events[4].end, doc.events[5].start), (11000, 11000))
        self.assertEqual(doc.events[5].text, "Ama bu ikinci satır kırk iki karakteri aşıyor gerçekten")

    def test_cancel_leaves_doc(self):
        data = open(SAMPLE, "rb").read()
        doc, r = self.run_m("Test/iptal", [0])
        self.assertEqual(r.status, "cancel")
        self.assertEqual(doc.to_bytes(), data)

    def test_error_leaves_doc(self):
        data = open(SAMPLE, "rb").read()
        doc, r = self.run_m("Test/hata", [0])
        self.assertEqual(r.status, "error")
        self.assertIn("attempt to index", r.error)
        self.assertIn("test_macros.lua", r.error)
        self.assertEqual(doc.to_bytes(), data)

    def test_readonly_macro_byte_identical(self):
        doc, r = self.run_m("Test/salt-okuma", [0])
        self.assertFalse(r.changed)
        self.assertEqual(doc.to_bytes(), open(SAMPLE, "rb").read())

    def test_untouched_lines_keep_raw(self):
        doc, r = self.run_m("Test/re", [1])
        self.assertTrue(r.changed)
        out = doc.to_bytes().decode("utf-8-sig")
        self.assertIn("Dialogue: 0,0:00:01.00,0:00:03.50,Default,Ali,0000,0000,0000,,{\\an8}", out)
        self.assertIn("; arada yorum satırı", out)

    def test_dialog_answers(self):
        self.host.dialog_answers.append(("Tamam", {"txt": "ğüşi", "up": True, "n": 7}))
        doc, r = self.run_m("Test/dialog", [0])
        self.assertEqual(doc.events[0].text, "ĞÜŞI#7")
        doc, r = self.run_m("Test/dialog", [0])
        self.assertEqual(doc.events[0].text, "varsayılan#3")
        self.host.dialog_answers.append(("İptal", {}))
        doc, r = self.run_m("Test/dialog", [0])
        self.assertEqual(r.status, "cancel")

    def test_info_and_styles(self):
        doc, r = self.run_m("Test/info-style", [0])
        self.assertEqual(doc.get_info("Title"), "Yeni Başlık")
        self.assertEqual(doc.get_info("OsiTest"), "1")
        self.assertEqual([s.name for s in doc.styles], ["Default", "Sign", "Yeni"])
        self.assertEqual(doc.styles[1].fontsize, 66.5)
        out = doc.to_text()
        self.assertIn("; Script generated by Aegisub 3.2.2", out)
        # Default stilinin ham satırı (0080 kenar) korunmalı
        self.assertIn("Style: Default,Arial,72,&H00FFFFFF,&H000000FF,&H00000000,&H64000000,-1,0,0,0,100,100,0,0,1,3.5,1.5,2,0080,80,50,1", out)

    def test_validation(self):
        m = macro(self.sc, "Test/kare")
        doc = AssDocument.load(SAMPLE)
        self.assertEqual(self.sc.validate(m, doc, [0, 1], 0), (False, "tek satır"))
        self.assertEqual(self.sc.validate(m, doc, [1], 1), (True, "tek satır"))

    def test_frames(self):
        self.host.frame_map = FrameMap.from_fps(24000 / 1001, 2000)
        try:
            doc, r = self.run_m("Test/kare", [0])
            f, ms = doc.events[0].effect.split(",")
            self.assertEqual(int(f), 24)          # 1000 ms -> START karesi 24 (23.976 fps)
            self.assertEqual(int(ms), self.host.frame_map.ms_from_frame(24))
        finally:
            self.host.frame_map = None

    def test_karaskel(self):
        doc, r = self.run_m("Test/karaskel", [5])
        self.assertEqual(r.status, "ok", r.error)
        parts = doc.events[5].effect.split("|")
        self.assertEqual([p.split(":")[0] for p in parts], ["Ka", "ra", "o", "ke"])
        self.assertEqual([int(p.split(":")[1]) for p in parts], [0, 200, 500, 750])
        self.assertTrue(all(int(p.split(":")[2]) > 0 for p in parts))


class TestBundledAegisubScripts(unittest.TestCase):
    """Aegisub ile gelen autoload betikleri değiştirilmeden çalışmalı."""

    def test_all_load_and_run(self):
        files = sorted(glob.glob(os.path.join(config.builtin_lua_dir(), "autoload", "*.lua")))
        self.assertGreaterEqual(len(files), 6)
        for p in files:
            host = HeadlessHost()
            sc = load(p, host)
            for m in sc.macros:
                doc = AssDocument.load(SAMPLE)
                if "template" in m.name.lower():
                    doc.events.append(Event(comment=True, effect="template syl", text="{\\pos($x,$y)}"))
                r = sc.run_macro(m, doc, [0, 3, 5], 0)
                self.assertIn(r.status, ("ok",), f"{os.path.basename(p)} / {m.name}: {r.error}")

    def test_strip_tags_result(self):
        sc = load(os.path.join(config.builtin_lua_dir(), "autoload", "strip-tags.lua"))
        doc = AssDocument.load(SAMPLE)
        sc.run_macro(sc.macros[0], doc, [0, 5], 0)
        self.assertEqual(doc.events[0].text, "Merhaba dünya, nasılsın?")
        self.assertEqual(doc.events[5].text, "Karaoke")

    def test_templater_generates_fx(self):
        sc = load(os.path.join(config.builtin_lua_dir(), "autoload", "kara-templater.lua"))
        doc = AssDocument.load(SAMPLE)
        doc.events.append(Event(comment=True, effect="template syl noblank", text="{\\pos($x,$y)}"))
        r = sc.run_macro(sc.macros[0], doc, [0], 0)
        self.assertEqual(r.status, "ok", r.error)
        fx = [e for e in doc.events if e.effect == "fx"]
        kara = [e.text for e in fx if e.start == 12000]
        self.assertEqual(len(kara), 4)
        self.assertTrue(all(t.startswith("{\\pos(") for t in kara))


class TestScriptManager(unittest.TestCase):
    def test_discover_dedup(self):
        d = config.builtin_autoload_dirs()[0]
        mgr = ScriptManager([d, d], INC, HeadlessHost())
        mgr.load_all()
        names = [os.path.basename(s.path) for s in mgr.scripts]
        self.assertEqual(len(names), len(set(names)))
        self.assertTrue(mgr.find_macro("Strip tags"))

    def test_broken_script_reports_error(self):
        import tempfile
        p = os.path.join(tempfile.mkdtemp(), "bozuk.lua")
        with open(p, "w", encoding="utf-8") as f:
            f.write("script_name='x'\nfunction (\n")
        sc = LuaScript(p, INC, HeadlessHost())
        self.assertFalse(sc.load())
        self.assertIn("bozuk.lua", sc.error)

    def test_bom_and_turkish_path(self):
        import tempfile
        d = os.path.join(tempfile.mkdtemp(), "Masaüstü çalışma")
        os.makedirs(d)
        p = os.path.join(d, "türkçe.lua")
        with open(p, "wb") as f:
            f.write(b"\xef\xbb\xbf" + "script_name='Türkçe'\naegisub.register_macro('Ç', '', function() end)\n".encode())
        with open(os.path.join(d, "yardimci.lua"), "w", encoding="utf-8") as f:
            f.write("YARDIM = 42\n")
        with open(p, "ab") as f:
            f.write(b"include('yardimci.lua')\nassert(YARDIM == 42)\n")
        sc = LuaScript(p, INC, HeadlessHost())
        self.assertTrue(sc.load(), sc.error)
        self.assertEqual(sc.name, "Türkçe")


